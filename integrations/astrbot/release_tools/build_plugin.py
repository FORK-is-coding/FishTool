"""组装发布树：plugin/ + 引擎快照 + 视图转换产物 + engine_requirements.txt。

用法::

    python integrations/astrbot/release_tools/build_plugin.py --out dist/plugin --version 0.1.0

只读取仓库文件，输出到 --out；不修改仓库中任何文件。
"""
from __future__ import annotations

import argparse
import fnmatch
import logging
import re
import shutil
import subprocess
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from release_tools.transform_views import transform_views  # noqa: E402

logger = logging.getLogger("fishtool.build")

ASTRBOT_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = ASTRBOT_DIR.parent.parent
PLUGIN_SRC = ASTRBOT_DIR / "plugin"
MANIFEST = Path(__file__).with_name("engine_manifest.txt")

#: FishTool requirements.txt 中引擎运行时不需要的包（运行时代码均不引用；PySide6 只用于桌面版）。
ENGINE_REQ_DROP = {"pyside6", "websocket-client", "requests"}

_ALWAYS_SKIP_DIRS = {"__pycache__", ".pytest_cache"}
_ALWAYS_SKIP_SUFFIX = {".pyc", ".pyo"}


def _read_manifest(path: Path = MANIFEST) -> tuple[list[str], list[str]]:
    includes: list[str] = []
    excludes: list[str] = []
    for raw in path.read_text("utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("!"):
            excludes.append(line[1:].strip())
        else:
            includes.append(line)
    return includes, excludes


def _excluded(rel: str, excludes: list[str]) -> bool:
    for pattern in excludes:
        if pattern.endswith("/**"):
            prefix = pattern[:-3].rstrip("/") + "/"
            if rel.startswith(prefix):
                return True
        elif fnmatch.fnmatch(rel, pattern):
            return True
    return False


def iter_engine_files(repo_root: Path = REPO_ROOT) -> list[Path]:
    """按白名单列出引擎快照文件（相对仓库根）。

    Returns:
        list[Path]: 相对路径列表，已排序。
    """
    includes, excludes = _read_manifest()
    files: list[Path] = []
    for entry in includes:
        src = repo_root / entry
        if entry.endswith("/"):
            if not src.is_dir():
                raise FileNotFoundError(f"manifest dir missing: {entry}")
            candidates = [p for p in src.rglob("*") if p.is_file()]
        else:
            if not src.is_file():
                raise FileNotFoundError(f"manifest file missing: {entry}")
            candidates = [src]
        for path in candidates:
            rel = path.relative_to(repo_root)
            if any(part in _ALWAYS_SKIP_DIRS for part in rel.parts) or path.suffix in _ALWAYS_SKIP_SUFFIX:
                continue
            if _excluded(rel.as_posix(), excludes):
                continue
            files.append(rel)
    return sorted(set(files))


def copy_engine_snapshot(repo_root: Path, dst: Path) -> int:
    """把引擎快照复制到 dst（会先清空 dst）。

    Returns:
        int: 复制的文件数。
    """
    if dst.exists():
        shutil.rmtree(dst)
    files = iter_engine_files(repo_root)
    for rel in files:
        target = dst / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(repo_root / rel, target)
    return len(files)


def build_engine_requirements(repo_root: Path = REPO_ROOT) -> str:
    """由 FishTool requirements.txt 生成引擎 venv 依赖（去掉桌面/未用依赖，保留锁定版本）。"""
    # 注释保持 ASCII：pip 在中文 Windows 上可能按 GBK 解码 requirements 文件。
    out = [
        "# Generated by integrations/astrbot/release_tools/build_plugin.py from FishTool requirements.txt. Do not edit.",
        "# Dropped: PySide6 / websocket-client / requests (not used by the engine at runtime).",
    ]
    for raw in (repo_root / "requirements.txt").read_text("utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        name = re.split(r"[\[=<>!~ ;]", line, maxsplit=1)[0].strip().lower()
        if name in ENGINE_REQ_DROP:
            continue
        out.append(line)
    return "\n".join(out) + "\n"


def _git(repo_root: Path, *args: str) -> str:
    try:
        return subprocess.run(
            ["git", *args], cwd=repo_root, capture_output=True, text=True, check=True
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError) as exc:
        logger.warning("git %s failed: %s", " ".join(args), exc)
        return ""


def _set_metadata_version(metadata: Path, version: str) -> None:
    text = metadata.read_text("utf-8")
    new, count = re.subn(r"(?m)^version:\s*.*$", f"version: {version}", text)
    if count != 1:
        raise ValueError("metadata.yaml must contain exactly one top-level version line")
    metadata.write_text(new, "utf-8")


def build(out: Path, version: str | None = None, repo_root: Path = REPO_ROOT) -> Path:
    """构建发布树。

    Args:
        out: 输出目录（会被清空）。
        version: 写入 metadata.yaml 的版本号；None 则保留源文件中的版本。
        repo_root: FishTool 仓库根。

    Returns:
        Path: 输出目录。
    """
    out = out.resolve()
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(
        PLUGIN_SRC,
        out,
        ignore=shutil.ignore_patterns("__pycache__", "*.pyc", ".gitkeep"),
    )
    count = copy_engine_snapshot(repo_root, out / "engine" / "fishtool")
    commit = _git(repo_root, "rev-parse", "HEAD")
    describe = _git(repo_root, "describe", "--tags", "--always", "--dirty")
    (out / "engine" / "VERSION").write_text(f"{commit or 'unknown'} {describe or ''}".strip() + "\n", "utf-8")
    (out / "engine_requirements.txt").write_text(build_engine_requirements(repo_root), "utf-8")
    # 插件包内含 FishTool 引擎快照，必须随附仓库许可证；发布到插件仓库时会整树替换，
    # 不带 LICENSE 会把目标仓库已有的许可证文件删掉。
    shutil.copy2(repo_root / "LICENSE", out / "LICENSE")

    views_out = out / "views" / "console"
    transform_views(
        repo_root / "web" / "frontend",
        ASTRBOT_DIR / "frontend_shim",
        views_out,
    )
    if version:
        _set_metadata_version(out / "metadata.yaml", version)
    logger.info("built plugin at %s (engine files: %d, engine %s)", out, count, commit[:8])
    return out


def main(argv: list[str] | None = None) -> int:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default="dist/plugin")
    parser.add_argument("--version", default=None)
    args = parser.parse_args(argv)
    version = (args.version or "").strip() or None
    if version and not re.fullmatch(r"\d+\.\d+\.\d+([.-][0-9A-Za-z.]+)?", version):
        parser.error(f"invalid version: {version}")
    build(Path(args.out), version)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
